-- ============================================================
-- Employee Pipeline
-- Redshift Staging Table
--
-- Purpose:
--   Holds only the current Silver batch before SCD Type 2
--   processing into curated.dim_employee.
--
-- Loading pattern:
--   TRUNCATE staging.stg_employee
--   -> Load current Silver batch
--   -> Run curated SCD2 stored procedure
-- ============================================================
CREATE TABLE IF NOT EXISTS staging.stg_employee
(
    emp_id               INTEGER,
    emp_name             VARCHAR(200),
    age                  INTEGER,
    gender               VARCHAR(50),
    department_name      VARCHAR(100),
    position             VARCHAR(150),
    salary               DECIMAL(12,2),
    joining_date         DATE,
    experience_years     DECIMAL(5,2),
    created_at           TIMESTAMP,
    updated_at           TIMESTAMP,
    -- Derived business attributes
    age_band             VARCHAR(50),
    experience_band      VARCHAR(50),
    -- SHA-256 hash generated by the Silver -> Staging Glue job.
    -- Used later to detect SCD Type 2 business changes.
    stg_business_hash    VARCHAR(64)
);
